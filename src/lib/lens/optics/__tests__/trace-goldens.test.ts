// THE SAFETY NET, modelled on ops/__tests__/recipe-goldens.test.ts. Every probe
// ray's FULL-TRACE output, pinned as literals: the probe grid × focus {0,1} ×
// aperture {0,0.3,1} × iorShift {−d,0,+d}, as (dirX, dirY, dirZ, alive) on the
// NUM backend.
//
// It exists to make a REFACTOR provable. trace-laws.test.ts states the trace's
// properties one at a time — the warpGain identity, the focus no-op, the
// aperture monotonicity — and a rewrite of the intersect/refract internals can
// satisfy every one of them while quietly moving the glass. This table cannot
// be satisfied by anything but the same arithmetic: it was generated by RUNNING
// the trace, so it carries no derivation of its own and is never "re-derived".
// A row that moves is a behaviour change, and the commit that moves it has to
// say why — including a re-measured PRESCRIPTION, which moves all of them.
//
// TO REGENERATE (after a deliberate change, or after re-measuring the table):
//   LENS_TRACE_REGEN=1 npx vitest run src/lib/lens/optics/__tests__/trace-goldens.test.ts
// and paste the printed array over GOLDEN below.
//
// Tolerance is 1e-9 (nine places) — far below anything visible in a bent ray,
// far above the last ulp of a chain that rebuilds these through 21 surfaces.
//
// SANITY, checked against paraxial expectations when this table was generated
// (recorded, not asserted — the rows themselves are the assertion):
//   • the eighteen x = 0, tilt = 0 rows read [0, −1, 0, 1] EXACTLY: an on-axis
//     ray leaves on-axis at every focus, aperture and dispersion shift;
//   • the FIELD FLIP is pinned by the table, not just by trace-laws (g): all
//     six x = 3, tilt = 0, aperture = 0 rows are alive with dirX < 0 (−0.55
//     to −0.48), i.e. a ray entering parallel above the axis leaves bent
//     across it. Its mirror at x = −6 is NOT pinned here — it dies on GLASS,
//     Element_06's 5.802mm rear at r = 6.139, so no aperture setting can
//     revive it. The negative half of the flip stays pinned by law (g) at
//     x = −3, which does survive;
//   • 54 of the 270 rows are alive, and the count falls monotonically with the
//     aperture channel exactly as trace-laws (c) requires: 24/90 wide open,
//     18/90 at 0.3 (a 4.42mm door), 12/90 at 1 (1.20mm). The grid stays harsh
//     because the narrowest glass in the stack is that 5.802mm E06 rear;
//   • within each alive (x, tilt, focus, aperture) group the three dispersion
//     rows move monotonically and by at most 1.65e-2 in any component: a small
//     perturbation, which is what a 0.015 index offset should be.
// Dead rows still carry a direction (the trace is branch-free and keeps
// refracting), so their dir values are pinned but carry no optical meaning.

