  for (const [name, recipe] of Object.entries(RECIPES)) {
    it(`(g) ${name} reproduces every pinned row`, () => {
      const rows = GOLDEN[name as RecipeName];
      let i = 0;
      for (const p of PIECES) {
        for (const v of PROBES) {
          for (const channel of CHANNELS) {
            const knobs = recipe.knobDefaults;
            const gateAt = (c: number): { flight: number; stick: number } =>
              gate(NUM, recipe.gateSpec(knobs), c, {
                rank01: p.rank01,
                layerPhase: p.layerPhase,
              });
            const ctx = ctxOf(p, v, channel, gateAt, gateAt(channel));
            const seated: VertexState<number> = {
              ...atPolar(ctx.t0 + ctx.phi, ctx.R + ctx.off),
              axial: ctx.yN * 40,
              rot: 0,
              aim: ctx.t0,
              rem: 0,
            };
            const frame0: PieceFrame<number> = {
              ...atPolar(p.t0, p.R),
              axial: 0,
              orient: p.t0,
            };
            const out = runPipeline(
              recipe.build(ctx, knobs),
              seated,
              frame0,
              ctx,
            ).v;
            const g = rows[i++]!;
            const at = `${name} t0=${p.t0} frac=${v.frac} ch=${channel}`;
            const pol = polarOf(out);
            expect(pol.theta, `${at} theta`).toBeCloseTo(g[0], 9);
            expect(pol.radius, `${at} radius`).toBeCloseTo(g[1], 9);
            expect(out.axial, `${at} axial`).toBeCloseTo(g[2], 9);
            expect(out.rot, `${at} rot`).toBeCloseTo(g[3], 9);
          }
        }
      }
      expect(i).toBe(rows.length);
    });
  }
