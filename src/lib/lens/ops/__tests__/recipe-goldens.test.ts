// THE SAFETY NET. Every recipe's FULL-PIPELINE output, pinned as literals: the
// four recipes × three pieces × seven probe vertices (five across the sheet, two
// overrunning it) × four channel positions, as (theta, radius, axial, rot) on
// the NUM backend.
//
// It exists to make a REFACTOR provable. The other suites in this folder each
// state one law — the channel-0 identity, the weight fold, the wrap's
// calibration — and a rewrite of the op internals can satisfy every one of them
// while quietly moving the model. This table cannot be satisfied by anything but
// the same arithmetic: it was generated by RUNNING the pipeline, so it carries
// no derivation of its own and is never "re-derived". A row that moves is a
// behaviour change, and the commit that moves it has to say why.
//
// Tolerance is 1e-9 (nine places) — far below the instrument's 0.01mm quantum,
// far above the last ULP of a chain that rebuilds these through trig.
//
// A row that moves is a behaviour change, and the commit that moves it says
// why: the `explode` block last moved for the ending's staggered spiral (its
// gate gained a per-piece stagger, so partial-channel rows move and the
// saturated ones do not).

