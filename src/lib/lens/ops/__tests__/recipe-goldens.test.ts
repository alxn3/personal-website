function ctxOf(
  p: Piece,
  v: Probe,
  channel: number,
  gateAt: OpCtx<number>["gateAt"],
  phase: { flight: number; stick: number },
): OpCtx<number> {
  const L = p.R * 2 * HALF;
  const d = v.frac * L;
  return {
    A: NUM,
    channel, // the recipe's own clock; `gateAt` is its own gate, re-runnable
    gateAt,
    t0: p.t0,
    R: p.R,
    rank01: p.rank01,
    layerPhase: p.layerPhase,
    halfSpan: HALF,
    partClass: PART_CLASS.structure,
    phi: HALF - d / p.R, // the house from = −1 ⇒ d = R·(halfSpan − phi)
    d,
    L,
    yN: v.yN,
    off: v.off,
    rung: p.rung,
    axi: 0,
    layerN: 5,
    adopted: 0,
    flight: phase.flight,
    stick: phase.stick,
    wrapDir: WRAP_DIR,
  };
}

